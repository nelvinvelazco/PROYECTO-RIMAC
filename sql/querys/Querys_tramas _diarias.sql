        SUBSTR(TRAMA_ORIGINAL, 80, 30) AS APELLIDO_MATERNO,
        SUBSTR(TRAMA_ORIGINAL, 110, 30) AS NOMBRES, FECHA_DE_INICIO_DEL_SEGURO, 
