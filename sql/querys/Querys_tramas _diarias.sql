WITH conteo_productos AS(
    SELECT FORMAT_DATE('%Y-%m', fecha_declarada) AS MES, TIPO_DE_SEGURO, TIPO_DE_MOVIMIENTO, 
        COUNT(DISTINCT NOMBRE_DE_ARCHIVO) AS CANT_TRAMAS, count(*) AS CANT_REG
    FROM `produccion.tramas_diarias_2025_Archivo`
    GROUP BY MES, TIPO_DE_SEGURO, TIPO_DE_MOVIMIENTO
    ORDER BY MES, TIPO_DE_SEGURO, TIPO_DE_MOVIMIENTO
)
SELECT MES, C.TIPO_DE_SEGURO, P.NOMBRE_PRODUCTO, C.TIPO_DE_MOVIMIENTO, C.CANT_TRAMAS, C.CANT_REG
FROM conteo_productos C
LEFT JOIN `produccion.PRODUCTOS` P ON C.TIPO_DE_SEGURO = P.COD_PRODUCTO
ORDER BY MES, TIPO_DE_SEGURO, TIPO_DE_MOVIMIENTO;

