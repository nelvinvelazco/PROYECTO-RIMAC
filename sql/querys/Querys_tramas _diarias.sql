SELECT
  EXTRACT(YEAR FROM FECHA_DE_AFILIACION) AS ANIO, 
  EXTRACT(MONTH FROM FECHA_DE_AFILIACION) AS MES, 
  TIPO_DE_SEGURO, 
  TIPO_DE_MOVIMIENTO, 
  TIPO_DE_REGISTRO, 
  MONEDA, 
  COUNT(
    CASE 
      WHEN TIPO_DE_SEGURO = '825' AND TIPO_DE_MOVIMIENTO = '1' AND TIPO_DE_REGISTRO = '07' THEN 1
      WHEN TIPO_DE_SEGURO = '825' AND TIPO_DE_MOVIMIENTO = '4' AND TIPO_DE_REGISTRO = '00' THEN 1
      WHEN TIPO_DE_SEGURO = '825' AND TIPO_DE_MOVIMIENTO = '4' AND TIPO_DE_REGISTRO = '01' THEN 1
      WHEN TIPO_DE_SEGURO != '825' THEN 1
    END
  ) AS CANTIDAD,
  SUM(
    CASE 
      WHEN TIPO_DE_SEGURO = '825' AND TIPO_DE_MOVIMIENTO = '1' AND TIPO_DE_REGISTRO = '07' THEN PRIMA_BRUTA
      WHEN TIPO_DE_SEGURO = '825' AND TIPO_DE_MOVIMIENTO = '4' AND TIPO_DE_REGISTRO = '00' THEN PRIMA_BRUTA
      WHEN TIPO_DE_SEGURO = '825' AND TIPO_DE_MOVIMIENTO = '4' AND TIPO_DE_REGISTRO = '01' THEN PRIMA_BRUTA
      WHEN TIPO_DE_SEGURO != '825' THEN PRIMA_BRUTA
    END
  ) AS TOTAL_PRIMA
FROM (
    SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2021`
    UNION ALL
    SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2022`
    UNION ALL
    SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2023`
    UNION ALL
    SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2024`
    UNION ALL
    SELECT * FROM `produccion.TRAMAS_diarias_BBVA_2025`
    )
WHERE FECHA_DE_AFILIACION BETWEEN '2023-01-01' AND '2025-12-31'
  AND TIPO_DE_MOVIMIENTO IN ('1','4')
GROUP BY ANIO, MES, TIPO_DE_SEGURO, TIPO_DE_MOVIMIENTO, TIPO_DE_REGISTRO, MONEDA
ORDER BY ANIO, MES, TIPO_DE_SEGURO;

